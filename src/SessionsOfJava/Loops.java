package SessionsOfJava;

public class Loops {
    public static void main(String[] args) {

        // for loop
       for( int i=1 ; i<=10 ; i++ )
            System.out.println(i);


        // while loop
        int j=30;
        while (j>=20)
        {
            System.out.println(j);
            j--;
        }

        // do while loop
        int x=5;
        do {
            System.out.println(x);
            x++;
        }
        while (x<=20);

    }
}
