package SessionsOfJava;

public class Void_functions {
    public static void main(String[] args)
    {
        // Function Calling

        sum(5 , 8);
        sum( 10 , 20);

    }

    // Function declaration ( void function means no return to store in variable)
    public static void sum ( int x , int y)
    {
        System.out.println(x+y);
    }
}
